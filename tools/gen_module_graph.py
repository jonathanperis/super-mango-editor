#!/usr/bin/env python3
"""Write the module dependency tables in docs/wiki/architecture.md.

The tables come from the code, so they cannot drift: every `#include "..."`
line under src/ is resolved to the file it names, each file is grouped by its
directory (src/core, src/levels, ...; files directly in src/ form "src"), and
the tables list which directories each one reaches into. The second table is
the list of game files the editor also compiles, read from the Makefile's
EDITOR_SRCS.

    python3 tools/gen_module_graph.py          # rewrite the block in place
    python3 tools/gen_module_graph.py --check  # fail when the block is stale

`make docs-drift` runs the check, so a new #include that crosses directories
shows up as a one-line diff in the manual.
"""

from __future__ import annotations

import argparse
import glob
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
PAGE = ROOT / "docs" / "wiki" / "architecture.md"
START = "<!-- module-graph:start (generated by tools/gen_module_graph.py; do not edit by hand) -->"
END = "<!-- module-graph:end -->"
INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.M)


def module_of(path: Path, src: Path = SRC) -> str:
    """"src" for files directly in src/, otherwise "src/<first directory>"."""
    rel = path.relative_to(src)
    return "src" if len(rel.parts) == 1 else f"src/{rel.parts[0]}"


def source_files(src: Path = SRC) -> list[Path]:
    return sorted(p for p in src.rglob("*") if p.suffix in {".c", ".h"} and p.is_file())


def include_edges(src: Path = SRC) -> dict[str, set[str]]:
    """module -> the other modules its files include. Includes that resolve
    outside src/ (vendor headers such as tomlc17.h, raylib) are left out."""
    src = src.resolve()
    edges: dict[str, set[str]] = {}
    for path in source_files(src):
        here = module_of(path, src)
        edges.setdefault(here, set())
        for name in INCLUDE_RE.findall(path.read_text(encoding="utf-8")):
            target = (path.parent / name).resolve()
            if not target.is_file() or src not in target.parents:
                continue
            other = module_of(target, src)
            if other != here:
                edges[here].add(other)
    return edges


def makefile_var(makefile: str, name: str) -> str:
    """The right-hand side of `NAME = ...`, with backslash continuations joined."""
    match = re.search(rf"^{name}\s*:?=\s*((?:.*\\\n)*.*)$", makefile, re.M)
    return match.group(1).replace("\\\n", " ") if match else ""


def editor_game_sources(root: Path = ROOT) -> list[str]:
    """Files outside src/editor/ that the Makefile builds into the editor."""
    makefile = (root / "Makefile").read_text(encoding="utf-8")
    text = makefile_var(makefile, "EDITOR_SRCS")
    for var in ("EDITOR_DIR", "SHARED_DIR", "VENDOR_DIR"):
        text = text.replace(f"$({var})", makefile_var(makefile, var).strip())
    files: list[str] = []
    for word in text.split():
        if word == "$(wildcard":
            continue  # `$(wildcard src/shared/*.c)`: the pattern is the next word
        pattern = word.rstrip(")")
        files.extend(sorted(glob.glob(pattern, root_dir=root)) if "*" in pattern else [pattern])
    return sorted({f for f in files if f.startswith("src/") and not f.startswith("src/editor/")})


def render(src: Path = SRC, root: Path = ROOT) -> str:
    edges = include_edges(src)
    users: dict[str, set[str]] = {module: set() for module in edges}
    for module, targets in edges.items():
        for target in targets:
            users.setdefault(target, set()).add(module)
    counts: dict[str, int] = {}
    for path in source_files(src):
        counts[module_of(path, src)] = counts.get(module_of(path, src), 0) + 1

    def names(modules: set[str]) -> str:
        return ", ".join(f"`{m}`" for m in sorted(modules)) or "nothing"

    lines = [START, "",
             "| Directory | Files | Includes headers from | Included by |",
             "|-----------|-------|-----------------------|-------------|"]
    for module in sorted(edges):
        lines.append(f"| `{module}` | {counts.get(module, 0)} | {names(edges[module])} | {names(users[module])} |")
    shared = editor_game_sources(root)
    lines += ["", "Game files the editor also compiles (the Makefile's `EDITOR_SRCS`, outside `src/editor/`):", ""]
    lines += [f"- `{path}`" for path in shared]
    lines += ["", END]
    return "\n".join(lines)


def replace_block(page: str, block: str) -> str | None:
    if START not in page or END not in page:
        return None
    before = page.split(START, 1)[0]
    after = page.split(END, 1)[1]
    return before + block + after


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="fail when architecture.md is stale")
    args = parser.parse_args(argv)
    page = PAGE.read_text(encoding="utf-8")
    updated = replace_block(page, render())
    if updated is None:
        print(f"gen_module_graph: {PAGE.relative_to(ROOT)} has no module-graph markers", file=sys.stderr)
        return 1
    if args.check:
        if updated != page:
            print("gen_module_graph: docs/wiki/architecture.md module tables are stale; "
                  "run `make module-graph`", file=sys.stderr)
            return 1
        print("module graph: ok")
        return 0
    if updated != page:
        PAGE.write_text(updated, encoding="utf-8")
        print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
