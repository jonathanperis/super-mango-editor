#!/usr/bin/env python3
"""Write vendor/raygui/raygui_icons.h: the editor's icons from the pinned raygui.h.

Only the icon bitmaps are imported, not raygui's widgets. Each icon is
16 x 16 one-bit pixels in eight 32-bit words, low bit first, exactly as
raygui's GuiDrawIcon reads them.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "vendor/raygui/raygui_icons.h"

# The icons the editor draws: raygui's name, then ours (UI_ICON_<ours>).
ICONS = (
    ("ICON_CURSOR_CLASSIC", "SELECT"),
    ("ICON_PENCIL", "PLACE"),
    ("ICON_RUBBER", "DELETE"),
    ("ICON_GRID", "GRID"),
    ("ICON_INFO", "DEBUG"),
    ("ICON_LAYERS_ISO", "CAMPAIGN"),
    ("ICON_EYE_ON", "CONTRAST"),
    ("ICON_PLAYER_PLAY", "PLAY"),
    ("ICON_PLAYER_STOP", "STOP"),
    ("ICON_FILE_SAVE_CLASSIC", "SAVE"),
    ("ICON_FILE_SAVE", "SAVE_AS"),
    ("ICON_FOLDER_OPEN", "OPEN"),
    ("ICON_FILE_ADD", "NEW"),
    ("ICON_WAVE_SINUS", "FOG"),
)

WORDS = 8  # RAYGUI_ICON_DATA_ELEMENTS at the 16 px RAYGUI_ICON_SIZE


def icon_ids(source: str) -> dict[str, int]:
    names = source.split("} GuiIconName;", 1)[0].rsplit("typedef enum {", 1)[1]
    return {name: int(value) for name, value in re.findall(r"(ICON_\w+)\s*=\s*(\d+)", names)}


def icon_words(source: str) -> list[int]:
    start = "static unsigned int guiIcons[RAYGUI_ICON_MAX_ICONS*RAYGUI_ICON_DATA_ELEMENTS] = {"
    body = source.split(start, 1)[1].split("};", 1)[0]
    # Drop the comments, which name each row and contain no hex.
    body = re.sub(r"//[^\n]*", "", body)
    return [int(word, 16) for word in re.findall(r"0x[0-9a-fA-F]+", body)]


def render(source: str, pin: dict[str, str]) -> str:
    ids = icon_ids(source)
    words = icon_words(source)
    lines = [
        "/*",
        " * raygui_icons.h — icons from raygui " + pin["version"] + " (zlib license, see LICENSE).",
        " *",
        " * Generated by tools/import_raygui_icons.py from src/raygui.h at commit",
        " * " + pin["commit"] + "; do not edit.",
        " * Each icon is 16 x 16 one-bit pixels in eight words: bit k of word w is",
        " * the pixel at x = k % 16, y = 2 * w + k / 16, as in raygui's GuiDrawIcon.",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "typedef enum {",
        "    UI_ICON_NONE = 0,",
    ]
    lines += [f"    UI_ICON_{ours},{' ' * (10 - len(ours))}/* raygui {theirs} ({ids[theirs]}) */"
              for theirs, ours in ICONS]
    lines += ["    UI_ICON_COUNT", "} UIIcon;", "",
              "static const uint32_t raygui_icon_bits[UI_ICON_COUNT][8] = {",
              "    {0},"]
    for theirs, ours in ICONS:
        first = ids[theirs] * WORDS
        bits = words[first:first + WORDS]
        if len(bits) != WORDS or not any(bits):
            raise SystemExit(f"raygui.h has no pixels for {theirs}")
        lines.append("    {" + ", ".join(f"0x{word:08x}" for word in bits) + f"}}, /* {ours} */")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="a downloaded copy of the pinned raygui.h")
    args = parser.parse_args()
    pin = json.loads((ROOT / "vendor/raygui/manifest.json").read_text(encoding="utf-8"))
    if pin["commit"] not in pin["url"]:
        raise SystemExit("vendor/raygui/manifest.json: url is not raygui.h at the pinned commit")
    if args.source:
        payload = args.source.read_bytes()
    else:
        with urllib.request.urlopen(pin["url"], timeout=120) as response:
            payload = response.read()
    if hashlib.sha256(payload).hexdigest() != pin["sha256"]:
        raise SystemExit("raygui.h checksum mismatch")
    OUT.write_text(render(payload.decode("utf-8"), pin), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
