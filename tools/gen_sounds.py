# Peak is not loudness: a short noise burst reaches its peak only briefly, while
# a square wave sits at its peak the whole time. So noisy SFX peak at -3 dBFS,
# tonal ones lower and square blips lowest, which keeps their average (RMS)
# levels close together. Ambience sits below the effects; each level's
# music_volume then scales it further.
